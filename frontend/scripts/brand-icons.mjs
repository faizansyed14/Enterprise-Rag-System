  microsoft: ["lobe", "microsoft"],
  sharepoint: ["fluent", "SharepointLogoIcon"],
  onedrive: ["fluent", "OneDriveLogoIcon"],
  // model providers
  openai: ["lobe", "openai"],
  anthropic: ["lobe", "anthropic"],
  openrouter: ["lobe", "openrouter"],
  azure_openai: ["lobe", "azure"],
  azure_di: ["lobe", "azureai"],
  cohere: ["lobe", "cohere"],
  mistral: ["lobe", "mistral"],
  llamaparse: ["lobe", "llamaindex"],
  huggingface: ["lobe", "huggingface"],
  // model families (shown next to chat models, whichever provider serves them)
  claude: ["lobe", "claude"],
  gemini: ["lobe", "gemini"],
  gemma: ["lobe", "gemma"],
  meta: ["lobe", "meta"],
